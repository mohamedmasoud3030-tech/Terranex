#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Project-scoped file store for Creative Director.

Security contract:
- project_id is a strict slug, never a path;
- all project files are selected from a fixed allowlist;
- versions are integer directories generated by the engine;
- CLI callers cannot choose arbitrary read/write paths through this store.
"""
from __future__ import annotations

import json
import os
import re
import shutil
from pathlib import Path

ENGINE_DIR = Path(__file__).resolve().parent
OPS_ROOT = ENGINE_DIR.parent
DEFAULT_PROJECTS_ROOT = OPS_ROOT / "output" / "creative-projects"

PROJECT_ID_RE = re.compile(r"[a-z0-9][a-z0-9-]{0,63}\Z")

BRIEF = "brief.json"
PLAN = "plan.json"
SPEC = "spec.json"
MEMORY = "memory.json"
CAPTION = "caption.txt"
STORYBOARD = "storyboard.png"
DECISIONS = "decisions.jsonl"
RENDER_REPORT = "render-report.json"
CRITIC_REPORT = "critic-report.json"
RELOCATION_REPORT = "relocation-report.json"
CREATIVE_INPUT = "creative-input.json"
REVISION_INPUT = "revision-input.json"
VOICE_TRANSCRIPT = "voice-transcript.json"
VOICE_ASSET_NAMES = (
    "voice-input.wav", "voice-input.mp3", "voice-input.m4a",
    "voice-input.flac", "voice-input.ogg",
)

ALLOWED_FILES = {
    BRIEF, PLAN, SPEC, MEMORY, CAPTION, STORYBOARD, DECISIONS,
    RENDER_REPORT, CRITIC_REPORT, RELOCATION_REPORT,
    CREATIVE_INPUT, REVISION_INPUT, VOICE_TRANSCRIPT, *VOICE_ASSET_NAMES,
}
SNAPSHOT_FILES = (BRIEF, PLAN, SPEC, CAPTION, STORYBOARD, RENDER_REPORT, CRITIC_REPORT)


class ProjectStore:
    """Safe, allowlisted access to one creative project directory."""

    def __init__(self, project_id: str, projects_root: str | os.PathLike | None = None):
        if not isinstance(project_id, str) or not PROJECT_ID_RE.fullmatch(project_id):
            raise ValueError("project_id غير آمن: استخدم slug صغيرًا مثل cd-followup-20s")
        # basename is a second guard after the strict fullmatch; no separators survive.
        safe_id = os.path.basename(project_id)
        root = Path(projects_root).resolve() if projects_root is not None else DEFAULT_PROJECTS_ROOT.resolve()
        self.project_id = safe_id
        self.root = root
        self.dir = root / safe_id
        self.dir.mkdir(parents=True, exist_ok=True)

    def path(self, name: str) -> Path:
        if name not in ALLOWED_FILES:
            raise ValueError(f"اسم ملف غير مسموح في المشروع: {name}")
        base = os.path.basename(name)
        if base != name:
            raise ValueError(f"اسم ملف غير مسموح في المشروع: {name}")
        return self.dir / base

    def exists(self, name: str) -> bool:
        return self.path(name).is_file()

    def read_json(self, name: str) -> dict:
        with self.path(name).open(encoding="utf-8") as f:
            return json.load(f)

    def write_json(self, name: str, data: dict) -> None:
        with self.path(name).open("w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")

    def read_text(self, name: str) -> str:
        return self.path(name).read_text(encoding="utf-8")

    def write_text(self, name: str, text: str) -> None:
        self.path(name).write_text(text, encoding="utf-8")

    def append_event(self, kind: str, data: dict) -> None:
        from datetime import datetime, timezone
        event = {"at": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
                 "kind": kind, **data}
        with self.path(DECISIONS).open("a", encoding="utf-8") as f:
            f.write(json.dumps(event, ensure_ascii=False) + "\n")

    def first_existing(self, names: tuple[str, ...]) -> Path | None:
        for name in names:
            p = self.path(name)
            if p.is_file():
                return p
        return None

    def version_dir(self, version: int) -> Path:
        v = int(version)
        if v < 1 or v > 9999:
            raise ValueError("رقم الإصدار خارج النطاق")
        d = self.dir / "versions" / f"v{v:04d}"
        d.mkdir(parents=True, exist_ok=True)
        return d

    def snapshot(self, version: int) -> Path:
        d = self.version_dir(version)
        for name in SNAPSHOT_FILES:
            src = self.path(name)
            if src.is_file():
                shutil.copy2(src, d / name)
        return d

    def restore(self, version: int) -> None:
        d = self.version_dir(version)
        for name in SNAPSHOT_FILES:
            src = d / name
            if src.is_file():
                shutil.copy2(src, self.path(name))
