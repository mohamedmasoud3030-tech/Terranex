#!/usr/bin/env node
/**
 * Regenerates docs/design/ROUTE_REVIEW.md from the working tree.
 *
 * The route review quotes counts — tables, captions, headings, hand-rolled
 * cards, loading states. A hand-written document drifts from the tree the
 * moment the next commit lands, and a stale count in a review document is
 * worse than no count: it reads as a verified fact. So the document is
 * generated, and every number in it comes from reading the files at run time.
 *
 * Usage: node scripts/route-review.mjs [--check]
 *   --check  regenerate in memory and exit 1 if the committed file differs
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';

const ROOT = process.cwd();
const OUT = 'docs/design/ROUTE_REVIEW.md';

function walk(dir, acc = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, acc);
    else if (entry === 'page.tsx') acc.push(full);
  }
  return acc;
}

const count = (source, re) => (source.match(re) ?? []).length;

const rows = walk(join(ROOT, 'src/app'))
  .sort()
  .map((file) => {
    const source = readFileSync(file, 'utf8');
    const dir = dirname(file);
    const tables = count(source, /<table\b/g);
    // A table is "named" when a <caption> opens the table element itself.
    let captioned = 0;
    for (const m of source.matchAll(/<table\b[^>]*>/g)) {
      if (source.slice(m.index + m[0].length, m.index + m[0].length + 300).includes('<caption')) {
        captioned += 1;
      }
    }
    const exists = (name) => {
      try {
        statSync(join(dir, name));
        return true;
      } catch {
        return false;
      }
    };
    return {
      file,
      route: relative(join(ROOT, 'src/app'), dir).replaceAll('\\', '/'),
      lines: source.split('\n').length,
      h2: count(source, /<h2[ >]/g),
      tables,
      captioned,
      scope: count(source, /scope="col"/g),
      sections: count(source, /<Section\b/g),
      // Order-insensitive on purpose: <section id="x" className="card stack…">
      // escaped the old prefix match purely by attribute order.
      handrolled: [...source.matchAll(/<section\b[^>]*>/g)].filter((m) =>
        /className="card stack/.test(m[0]),
      ).length,
      empty: count(source, /className="[^"]*\bempty\b/g),
      status: count(source, /className="status/g),
      tabs: count(source, /href: '#/g),
      numcells: count(source, /className="num"/g),
      inline: count(source, /style=\{\{/g),
      loading: exists('loading.tsx'),
      error: exists('error.tsx'),
      dynamic: source.includes('force-dynamic'),
    };
  });

const sum = (key) => rows.reduce((total, row) => total + row[key], 0);
const label = (route) => (route === '(app)' ? '`/` (home)' : `\`/${route.replace('(app)', '').replace(/^\//, '')}\``);

const dynamicRoutes = rows.filter((row) => row.dynamic);
const dynamicWithLoading = dynamicRoutes.filter((row) => row.loading);
const workspaceRoutes = rows.filter((row) => row.route.startsWith('(app)'));
const withError = workspaceRoutes.filter((row) => row.error);

const doc = `# Route-by-route UI/UX review — \`design/ui-ux-upgrade\`

Generated by \`node scripts/route-review.mjs\` from the working tree. Do not edit
by hand: every number below is measured at generation time, and a count that
has drifted from the code is worse than no count at all.

## What the numbers say

- **${rows.length} route surfaces** (\`page.tsx\`) — the original brief assumed 25.
- **${sum('tables')} data tables in page files, ${sum('captioned')} with an accessible name**, plus
  ${sum('scope')} \`scope="col"\` header cells. Every table in \`src\` is named.
- **${sum('numcells')} figure cells** carry \`.num\` (tabular numerals, end-aligned in RTL).
- **${sum('inline')} inline \`style={{}}\`** in \`src\` — the visual system is tokens and classes only.
- **${dynamicWithLoading.length} of ${dynamicRoutes.length} \`force-dynamic\` routes have a loading state.**
- **${withError.length} of ${workspaceRoutes.length} workspace routes have a route-level \`error.tsx\`**; the one
  exception is the redirect-only \`/statements\` route.

## Per route

| Route | Lines | Tables | Named | \`<h2>\` | \`<Section>\` | hand-rolled cards | empty states | status pills | tabs | loading | error |
|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|:--:|:--:|
${rows
  .map(
    (r) =>
      `| ${label(r.route)} | ${r.lines} | ${r.tables} | ${r.captioned} | ${r.h2} | ${r.sections} | ` +
      `${r.handrolled} | ${r.empty} | ${r.status} | ${r.tabs} | ` +
      `${r.loading ? '✓' : r.dynamic ? '✗' : '—'} | ${r.error ? '✓' : '—'} |`,
  )
  .join('\n')}

\`loading\` is \`—\` for routes that are not \`force-dynamic\` and so render synchronously.
\`error\` is \`—\` where the route relies on the workspace-level error boundary.

## Where the pass is genuinely done

Applied to every route, and verified rather than asserted:

- **Money is unambiguous.** Every figure cell carries its currency, minor-unit bigint
  formatting and \`.num\` alignment. No \`Number(\`, \`parseFloat\`, \`parseInt\` or \`toFixed\`
  appears in the money paths.
- **Status is never colour alone.** \`.status::before\` renders a glyph per tone, and
  \`.tone-open\` / \`.tone-void\` stay distinguishable with colour removed. Tested.
- **No raw schema codes reach the screen.** Seven screens printed \`PENDING\`, \`OWNER\`,
  \`SUPERSEDED\`, \`DRAFT\` verbatim into an Arabic interface. \`recordStatusLabel()\` and
  \`roleLabel()\` now cover every value the migrations' CHECK constraints permit, and fall
  back to the raw code rather than to a guess.
- **Every table is nameable by a screen reader**, and every column header is scoped.
- **In-page navigation points somewhere.** A test parses each page's tab hrefs against the
  ids that page actually renders. It found one dead tab (\`close\`), four unreachable
  sections (\`livestock\`), a sector-gated section with no tab (\`revenue\`) and an
  anchor-less section (\`operations\`).
- **Every \`force-dynamic\` route has a loading state**, including the three auth pages,
  which await \`supabase.auth.getUser()\` before deciding whether to redirect.
- **Contrast is measured from the tokens** against every background a token can sit on,
  which found a real AA failure: \`--muted-2\` at 3.77:1 while carrying text.
- **Sector identity is distinct** across the three verticals (accent, ink, wash, edge per
  sector) on one shared system, so they read as related rather than as three products.
- **No dead weight.** Every class selector in \`globals.css\` is referenced somewhere; four
  exported components that no page ever used were removed, along with the spec text that
  advertised one of them as though it shipped.

## Where it is not done — the honest remainder

1. **\`<Section>\` adoption is ${sum('sections')} against ${sum('handrolled')} hand-rolled
   \`<section className="card stack">\`.** Every titled card section in the workspace now
   composes the primitive. The six that remain are deliberate: three page shells
   (\`shell-form*\` — an h1 form surface, not a titled section) and three heading-less
   content cards carrying a table inside a logical section. The counter itself was also
   order-blind — \`<section id="x" className="card stack">\` escaped it entirely, hiding
   twelve sections in close and pilot — and now reads attributes in any order.
2. **${sum('h2')} bare \`<h2>\`** rely on a global style rule rather than \`<Section>\`'s
   \`aria-labelledby\` association. Correct today, weaker than it should be.
3. **${sum('empty')} inline empty notes** remain, and they are the deliberate form:
   \`<p className="empty">\` centred one-liners inside sections that simply have no rows
   (\`EmptyState compact\` would start-align and bold them, which reads worse for a
   "nothing here" note). Every card-level empty state goes through \`<EmptyState>\`, and
   the guard is order-insensitive after two agriculture states escaped it by class order.
4. **No browser in the build sandbox.** Responsive behaviour, focus order and reduced-motion
   were checked by CSS inspection and tests, not by rendering. The 360px target is expressed
   in the breakpoints but has not been looked at on a phone.
5. **\`error.tsx\` exists on ${withError.length} of the ${workspaceRoutes.length} workspace routes.** The one
   exception is \`/statements\`, which is a redirect to the participants page (statements
   wait on the R14 policy pack) and renders nothing of its own — a route-level boundary
   there would be dead weight, so the workspace boundary is the correct net.
`;

const target = join(ROOT, OUT);
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    /* missing file is a difference */
  }
  if (current !== doc) {
    console.error(`[route-review] ${OUT} is out of date — run: node scripts/route-review.mjs`);
    process.exit(1);
  }
  console.log(`[route-review] ${OUT} is current`);
} else {
  writeFileSync(target, doc);
  console.log(`[route-review] wrote ${OUT} (${rows.length} routes)`);
}
